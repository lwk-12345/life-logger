# ---------------------------------------------------------------------------
# 待办三口令（[2026-10-13 收口]）
#
# 待办升级的**唯一**入口是这三个词表。其他一切（「记得…」「需要…」「明天要…」
# 「查一下…」）都不进待办，只记为想法(idea)或生活事件。
#
# 为什么要收口：实测 2026-10-12 单日堆出 253 条待办，绝大多数是随口一句话被
# 升级成的，既无法管理，也挤爆了徽章的 4 个显示槽。
#
# 顺序敏感：长词必须排在短词前面，否则正则会先匹配到短词把内容截断
# （历史坑：「记下来」被「记下」截成「来」）。
# ---------------------------------------------------------------------------
