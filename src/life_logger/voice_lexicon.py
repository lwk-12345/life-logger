# ---------------------------------------------------------------------------
# 营养口令（[2026-10-13]）—— 「念一次存一次」的入口。
#
# 用户原话：「要么它自己可以搜，要么我主动去汇报，让它在后台记忆一下」。
# 这条口令把**用户念出来的营养成分表**写进自建品牌库（四层查询链的第①层），
# 以后同样的话直接命中本地库、不再联网也不再靠模型估。
#
# 例：「记录营养 菲诺厚椰乳 每100克 94千卡 蛋白质1克 脂肪7克 碳水6.8克 钠82毫克」
#
# 顺序敏感同 TODO/HABIT：长词排在短词前面，否则正则会先匹配到短词把内容截断。
# ---------------------------------------------------------------------------
